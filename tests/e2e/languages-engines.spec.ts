import { _electron as electron, expect, test } from '@playwright/test';
import { mkdtemp, mkdir, writeFile, readFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import path from 'node:path';
import os from 'node:os';

test('language picker selects historical modes, associates extensions, imports grammars and persists custom languages', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('.monaco-editor')).toBeVisible();
  await page.keyboard.press('Control+n');
  await page.getByRole('textbox', { name: 'File path', exact: true }).fill('historical.f90');
  await page.getByRole('button', { name: 'OK', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Language mode', exact: true })).toHaveText('Fortran Free Form');
  await page.locator('.monaco-editor textarea').first().focus();
  await page.keyboard.insertText('program hello\nprint *, "hello"\nend program hello');
  await expect(page.locator('.monaco-editor .view-lines')).toContainText('program');
  await expect.poll(() => page.locator('.monaco-editor .view-line').first().locator('span span').count()).toBeGreaterThan(1);
  await page.getByRole('button', { name: 'Language mode', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search programming languages' }).fill('Plankalk');
  await page.getByRole('option', { name: /Plankalkül/ }).click();
  await expect(page.getByRole('button', { name: 'Language mode', exact: true })).toHaveText('Plankalkül');
  await page.getByRole('button', { name: 'Language mode', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search programming languages' }).fill('COBOL');
  await page.getByRole('checkbox', { name: /Use this mode/ }).check();
  await page.getByRole('option', { name: /^COBOL/ }).click();
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('23-code-languages-v1')!).state.associations['.f90'])).toBe('cobol');
  await page.getByRole('button', { name: 'Language mode', exact: true }).click();
  await page.getByText('Add any missing language or dialect', { exact: true }).click();
  await page.getByRole('textbox', { name: 'Custom language id', exact: true }).fill('test-dialect');
  await page.getByRole('textbox', { name: 'Custom language name', exact: true }).fill('Test historical dialect');
  await page.getByRole('textbox', { name: 'Custom language extensions', exact: true }).fill('.testdialect');
  await page.getByRole('button', { name: 'Add and select language', exact: true }).click();
  await page.getByLabel('Import language grammar', { exact: true }).setInputFiles({ name: 'test.tmLanguage.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ scopeName: 'source.testdialect', patterns: [{ match: '\\bprogram\\b', name: 'keyword.control.testdialect' }] })) });
  await expect.poll(() => page.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('23-code-languages-v1')!).state.grammars))).toContain('test-dialect');
  await page.getByRole('button', { name: 'Close language picker' }).click();
  await expect(page.getByRole('button', { name: 'Language mode', exact: true })).toHaveText('Test historical dialect');
  await expect.poll(() => page.locator('.monaco-editor .view-line').first().locator('span span').count()).toBeGreaterThan(1);
  const readContent = () => page.evaluate(() => JSON.parse(localStorage.getItem('23-code-workspace-v1')!).state.files.find((file: { path: string }) => file.path === 'historical.f90'));
  expect((await readContent()).content).toContain('program hello');
  await page.reload();
  await expect(page.getByRole('button', { name: 'Language mode', exact: true })).toHaveText('Test historical dialect');
  expect((await readContent()).content).toContain('program hello');
});

test('native game-engine connections detect projects, approve real commands and receive external-editor requests', async () => {
  test.skip(process.platform !== 'win32', 'Exercises Windows engine launch and single-instance handoff.');
  test.setTimeout(120000);
  const base = process.platform === 'win32' ? path.join(process.env.LOCALAPPDATA!, 'Temp/opencode') : os.tmpdir();
  const fixture = await mkdtemp(path.join(base, '23-code-engines-'));
  const profile = await mkdtemp(path.join(base, '23-code-engine-profile-'));
  for (const directory of ['Unreal Demo/Source', 'Unreal Demo/Intermediate', 'Unity Demo/ProjectSettings', 'Unity Demo/Assets', 'Godot Demo', '.23code']) await mkdir(path.join(fixture, directory), { recursive: true });
  await writeFile(path.join(fixture, 'Unreal Demo/Game.uproject'), '{"FileVersion":3}');
  await writeFile(path.join(fixture, 'Unreal Demo/Source/main.cpp'), '// external editor fixture\nint value = 42;\n');
  await writeFile(path.join(fixture, 'Unreal Demo/Intermediate/generated.cpp'), 'must not enter workspace snapshot');
  await writeFile(path.join(fixture, 'Unity Demo/ProjectSettings/ProjectVersion.txt'), 'm_EditorVersion: 6000.0.0f1');
  await writeFile(path.join(fixture, 'Godot Demo/project.godot'), '[application]\nconfig/name="Fixture"\n');
  const script = path.join(fixture, 'engine-fixture.ps1');
  await writeFile(script, 'Write-Output "ENGINE_FIXTURE_OK"\n$args | ForEach-Object { Write-Output "ENGINE_ARG:$_" }\n');
  const env: Record<string, string> = {};
  for (const [key, value] of Object.entries(process.env)) if (value !== undefined && key !== 'ELECTRON_RUN_AS_NODE') env[key] = value;
  const executablePath = process.env.IDE_PACKAGED_EXE;
  const args = executablePath ? [`--profile=${profile}`] : ['.', `--profile=${profile}`];
  const app = await electron.launch({ ...(executablePath ? { executablePath } : {}), args, env });
  try {
    await app.evaluate(({ dialog }, folder) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] });
      dialog.showMessageBox = async () => ({ response: 1, checkboxChecked: false });
      dialog.showMessageBoxSync = () => 1;
    }, fixture);
    const page = await app.firstWindow();
    await expect(page.locator('.monaco-editor')).toBeVisible();
    await page.getByRole('button', { name: 'Open folder', exact: true }).click();
    await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('23-code-workspace-v1')!).state.roots[0]?.kind)).toBe('local');
    const inventory = await page.evaluate(async () => window.desktop!.enginesList());
    expect(inventory.projects.map(project => project.kind).sort()).toEqual(['custom', 'godot', 'unity', 'unreal']);
    expect(await page.evaluate(async () => (await window.desktop!.refresh()).files.some(file => file.path.includes('Intermediate/')))).toBe(false);
    await page.getByRole('button', { name: 'Game Engines', exact: true }).click();
    const godot = inventory.projects.find(project => project.kind === 'godot')!;
    await page.getByRole('combobox', { name: 'Game engine project' }).selectOption(godot.id);
    await page.getByRole('textbox', { name: 'Engine executable', exact: true }).fill('powershell.exe');
    await page.getByText('Advanced arguments (JSON array)', { exact: true }).click();
    await page.getByRole('textbox', { name: 'Engine prefix arguments' }).fill(JSON.stringify(['-NoLogo', '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', script]));
    await page.getByRole('button', { name: 'Save engine connection', exact: true }).click();
    await expect(page.locator('.engine-view').getByRole('status')).toContainText('Connection saved');
    const config = JSON.parse(await readFile(path.join(fixture, '.23code/engines.json'), 'utf8'));
    expect(config.profiles[godot.id].executable).toBe('powershell.exe');
    await page.getByRole('button', { name: 'Run game', exact: true }).click();
    await expect.poll(async () => page.evaluate(async () => (await window.desktop!.terminalList()).map(terminal => terminal.backlog).join('\n')), { timeout: 20000 }).toContain('ENGINE_FIXTURE_OK');
    const transcript = await page.evaluate(async () => (await window.desktop!.terminalList()).map(terminal => terminal.backlog).join('\n'));
    expect(transcript).toContain('--path'); expect(transcript).toContain('Godot Demo');
    await page.evaluate(async () => { for (const terminal of await window.desktop!.terminalList()) await window.desktop!.terminalClose(terminal.id); });
    const unity = inventory.projects.find(project => project.kind === 'unity')!;
    await page.getByRole('combobox', { name: 'Game engine project' }).selectOption(unity.id);
    await page.getByRole('button', { name: 'Generate Unity build helper for review', exact: true }).click();
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('23-code-workspace-v1')!).state.files.some((file: { path: string; content: string }) => file.path === 'Unity Demo/Assets/Editor/Code23Build.cs' && file.content.includes('BuildPipeline.BuildPlayer')))).toBe(true);
    const main = path.join(fixture, 'Unreal Demo/Source/main.cpp');
    const executable = executablePath ?? await app.evaluate(() => process.execPath);
    const child = spawn(executable, [...args, '--workspace', fixture, '--open-file', main, '--line', '2', '--column', '5'], { env, stdio: 'ignore' });
    await new Promise<void>((resolve, reject) => { child.once('error', reject); child.once('exit', code => code === 0 ? resolve() : reject(new Error(`External editor handoff failed: ${code}`))); });
    await expect(page.getByRole('tab', { name: /main.cpp/ })).toBeVisible();
    await expect(page.locator('.statusbar')).toContainText('Ln 2, Col 5');
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('23-code-workspace-v1')!).state.files.find((file: { path: string }) => file.path === 'Unity Demo/Assets/Editor/Code23Build.cs').content)).toContain('BuildPipeline.BuildPlayer');
  } finally { await app.close(); }
});
