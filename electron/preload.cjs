const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('desktop', {
  aiRequest: (action, input) => ipcRenderer.invoke('ai:request', action, input),
  enginesList: () => ipcRenderer.invoke('engines:list'),
  engineChoose: directory => ipcRenderer.invoke('engines:choose', directory),
  engineSave: (id, profile, rootId) => ipcRenderer.invoke('engines:save', id, profile, rootId),
  engineRun: (id, action, rootId) => ipcRenderer.invoke('engines:run', id, action, rootId),
  externalPending: () => ipcRenderer.invoke('external:pending'),
  externalAccept: (id, replace) => ipcRenderer.invoke('external:accept', id, replace),
  externalReject: id => ipcRenderer.invoke('external:reject', id),
  openFolder: () => ipcRenderer.invoke('workspace:open'),
  refresh: () => ipcRenderer.invoke('workspace:refresh'),
  readFile: path => ipcRenderer.invoke('file:read', path),
  writeFile: (path, content, expected) => ipcRenderer.invoke('file:write', path, content, expected),
  saveAs: (name, content) => ipcRenderer.invoke('file:save-as', name, content),
  renameFile: (from, to) => ipcRenderer.invoke('file:rename', from, to),
  deleteFile: path => ipcRenderer.invoke('file:delete', path),
  run: command => ipcRenderer.invoke('shell:run', command),
  cancelCommand: () => ipcRenderer.invoke('shell:cancel'),
  gitStatus: () => ipcRenderer.invoke('git:status'),
  gitAction: (action, value) => ipcRenderer.invoke('git:action', action, value),
  addFolder: () => ipcRenderer.invoke('workspace:add'),
  workspaceRoots: () => ipcRenderer.invoke('workspace:roots'),
  selectRoot: id => ipcRenderer.invoke('workspace:select', id),
  removeRoot: id => ipcRenderer.invoke('workspace:remove', id),
  saveWorkspace: () => ipcRenderer.invoke('workspace:save'),
  loadWorkspace: () => ipcRenderer.invoke('workspace:load'),
  connectRemote: (spec, add) => ipcRenderer.invoke('workspace:remote', spec, add),
  fileUri: path => ipcRenderer.invoke('workspace:uri', path),
  virtualPath: (uri, rootId) => ipcRenderer.invoke('workspace:virtual', uri, rootId),
  terminalList: () => ipcRenderer.invoke('terminal:list'),
  terminalCreate: options => ipcRenderer.invoke('terminal:create', options),
  terminalWrite: (id, data) => ipcRenderer.invoke('terminal:write', id, data),
  terminalResize: (id, cols, rows) => ipcRenderer.invoke('terminal:resize', id, cols, rows),
  terminalClose: id => ipcRenderer.invoke('terminal:close', id),
  tasksList: () => ipcRenderer.invoke('tasks:list'),
  tasksRun: (label, file) => ipcRenderer.invoke('tasks:run', label, file),
  tasksStop: id => ipcRenderer.invoke('tasks:stop', id),
  extensionsList: () => ipcRenderer.invoke('extensions:list'),
  extensionsInstall: folder => ipcRenderer.invoke('extensions:install', folder),
  extensionsToggle: (id, enabled) => ipcRenderer.invoke('extensions:toggle', id, enabled),
  extensionsUninstall: id => ipcRenderer.invoke('extensions:uninstall', id),
  extensionCommands: () => ipcRenderer.invoke('extensions:commands'),
  extensionRun: (id, command, context) => ipcRenderer.invoke('extensions:run', id, command, context),
  languagesList: () => ipcRenderer.invoke('languages:list'),
  languagesRunning: () => ipcRenderer.invoke('languages:running'),
  languageStart: id => ipcRenderer.invoke('languages:start', id),
  languageStop: id => ipcRenderer.invoke('languages:stop', id),
  languageDocument: (id, document) => ipcRenderer.invoke('languages:document', id, document),
  languageRequest: (id, method, params) => ipcRenderer.invoke('languages:request', id, method, params),
  debugConfigurations: () => ipcRenderer.invoke('debug:configurations'),
  debugStart: (name, file, breakpoints) => ipcRenderer.invoke('debug:start', name, file, breakpoints),
  debugBreakpoints: (file, lines) => ipcRenderer.invoke('debug:breakpoints', file, lines),
  debugRequest: (command, args) => ipcRenderer.invoke('debug:request', command, args),
  debugStop: () => ipcRenderer.invoke('debug:stop'),
  onEvent: callback => {
    const listener = (_event, value) => callback(value);
    ipcRenderer.on('ide:event', listener);
    return () => ipcRenderer.removeListener('ide:event', listener);
  },
});
